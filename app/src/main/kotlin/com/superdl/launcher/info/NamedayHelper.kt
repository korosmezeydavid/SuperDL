    fun forToday(): String = forDate(Calendar.getInstance())

    fun forDate(calendar: Calendar): String {
        val key = String.format(
            Locale.US,
            "%02d-%02d",
            calendar.get(Calendar.MONTH) + 1,
            calendar.get(Calendar.DAY_OF_MONTH)
        )
        return NAMEDAYS[key].orEmpty()
    }

